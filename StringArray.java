public class StringArray 
{
    public static void main(String[] args)
    {
        String[] names = {"Ram", "Sita", "Ravi", "Priya"};

        System.out.println("String Array:");

        for(int i = 0; i < names.length; i++)
        {
            System.out.println(names[i]);
        }
    }
}
