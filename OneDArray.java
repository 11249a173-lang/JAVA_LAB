public class OneDArray
{
    public static void main(String[] args)
    {
        int[] arr = {10, 20, 30, 40, 50};

        System.out.println("Elements of One-Dimensional Array:");

        for(int i = 0; i < arr.length; i++)
        {
            System.out.print(arr[i] + " ");
        }
    }
}